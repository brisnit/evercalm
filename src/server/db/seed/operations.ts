export async function seedOperations(
  db: SeedDb,
  ctx: {
    organizationId: string
    slug: string
    locationIds: Map<string, string>
    locationTimeZones: Map<string, string>
    jobRoleIds: Map<string, string>
    employmentIds: Map<string, string>
    systemEvent: (
      action: string,
      summary: string,
      extra?: Partial<typeof schema.auditEvents.$inferInsert>,
    ) => void
  },
  now = new Date(),
): Promise<{ templates: number; runs: number; handoffs: number }> {
  const seed = SEEDS[ctx.slug]
  if (!seed) return { templates: 0, runs: 0, handoffs: 0 }
  const org = ctx.organizationId
  const person = (key: string) => {
    const id = ctx.employmentIds.get(key)
    if (!id) throw new Error(`Operations seed: unknown person ${key} in ${ctx.slug}`)
    return id
  }
  const place = (key: string) => ctx.locationIds.get(key)!
  const tzOf = (key: string) => ctx.locationTimeZones.get(key)!
  const stationRows = await db
    .select({
      id: schema.stations.id,
      locationId: schema.stations.locationId,
      name: schema.stations.name,
    })
    .from(schema.stations)
    .where(eq(schema.stations.organizationId, org))
  const station = (location: string, name: string) => {
    const row = stationRows.find((s) => s.locationId === place(location) && s.name === name)
    if (!row) throw new Error(`Operations seed: no station ${name} at ${location}`)
    return row.id
  }
  const HOUR = 3_600_000

  // --- templates, published --------------------------------------------------
  const templateIds = new Map<string, string>()
  const taskIds = new Map<string, string>()
  for (const t of seed.templates) {
    const templateId = newId()
    const versionId = newId()
    const publishedAt = new Date(now.getTime() - 9 * 24 * HOUR)
    templateIds.set(t.name, templateId)
    await db.insert(schema.opsTemplates).values({
      id: templateId,
      organizationId: org,
      name: t.name,
      kind: t.kind,
      createdByEmploymentId: person(t.author),
      createdAt: publishedAt,
    })
    await db.insert(schema.opsTemplateVersions).values({
      id: versionId,
      organizationId: org,
      templateId,
      versionNumber: 1,
      name: t.name,
      kind: t.kind,
      description: t.description ?? '',
      createdByEmploymentId: person(t.author),
    })
    for (const location of t.locations) {
      await db
        .insert(schema.opsVersionLocations)
        .values({ id: newId(), organizationId: org, versionId, locationId: place(location) })
    }
    for (const role of t.jobRoles ?? []) {
      await db.insert(schema.opsVersionJobRoles).values({
        id: newId(),
        organizationId: org,
        versionId,
        jobRoleId: ctx.jobRoleIds.get(role)!,
      })
    }
    for (const s of t.stations ?? []) {
      await db.insert(schema.opsVersionStations).values({
        id: newId(),
        organizationId: org,
        versionId,
        stationId: station(s.location, s.name),
      })
    }
    for (const [sectionPosition, section] of t.sections.entries()) {
      const sectionId = newId()
      await db.insert(schema.opsSections).values({
        id: sectionId,
        organizationId: org,
        versionId,
        title: section.title,
        position: sectionPosition,
      })
      for (const [position, task] of section.tasks.entries()) {
        const id = newId()
        taskIds.set(`${t.name}::${task.title}`, id)
        await db.insert(schema.opsTasks).values({
          id,
          organizationId: org,
          versionId,
          sectionId,
          position,
          title: task.title,
          instructions: task.instructions ?? '',
          required: !task.optional,
          responseType: task.response ?? 'check',
          timingAnchor: task.at[0] === 'end' ? 'shift_end' : 'shift_start',
          offsetMinutes: task.at[1],
          requiresVerification: task.verify ?? false,
          shared: task.shared ?? false,
        })
      }
    }
    await db
      .update(schema.opsTemplateVersions)
      .set({ status: 'published', publishedAt, publishedByEmploymentId: person(t.author) })
      .where(eq(schema.opsTemplateVersions.id, versionId))
    await db
      .update(schema.opsTemplates)
      .set({ publishedVersionId: versionId })
      .where(eq(schema.opsTemplates.id, templateId))
    ctx.systemEvent('ops_template.published', `Published version 1 of "${t.name}"`, {
      subjectType: 'ops_template',
      subjectId: templateId,
    })
  }

  // --- today's demo shifts ----------------------------------------------------
  const halfHour = 30 * 60_000
  const shiftIds = new Map<string, string>()
  for (const demo of seed.shifts) {
    const tz = tzOf(demo.location)
    const locationId = place(demo.location)
    let startsAt: Date
    let endsAt: Date
    if (demo.start === 'now') {
      startsAt = new Date(Math.floor(now.getTime() / halfHour) * halfHour - 2 * HOUR)
      endsAt = new Date(startsAt.getTime() + demo.minutes * 60_000)
    } else {
      const today = localDateOf(now, tz)
      startsAt = localTimeToInstant(today, parseTimeOfDay(demo.start)!, tz)!
      endsAt = new Date(startsAt.getTime() + demo.minutes * 60_000)
    }
    const employmentId = person(demo.person)
    const jobRoleId = ctx.jobRoleIds.get(demo.jobRole) ?? null
    const stationId = demo.station ? station(demo.location, demo.station) : null

    const [overlapping] = await db
      .select()
      .from(schema.shifts)
      .where(
        and(
          eq(schema.shifts.organizationId, org),
          eq(schema.shifts.assigneeEmploymentId, employmentId),
          eq(schema.shifts.status, 'active'),
          lt(schema.shifts.startsAt, endsAt),
          gt(schema.shifts.endsAt, startsAt),
        ),
      )
      .limit(1)

    if (overlapping) {
      // Their regular shift today becomes the demo shift, moved to the demo
      // window: nobody is on two shifts at once.
      await db
        .update(schema.shifts)
        .set({
          startsAt,
          endsAt,
          publishedStartsAt: startsAt,
          publishedEndsAt: endsAt,
          jobRoleId,
          stationId,
          publishedJobRoleId: jobRoleId,
          publishedStationId: stationId,
          publishedAssigneeEmploymentId: employmentId,
          publishedStatus: 'active',
          publishedAt: overlapping.publishedAt ?? now,
          publishedBreakMinutes: overlapping.breakMinutes,
          publishedNotes: overlapping.notes,
          publishedIsOpen: false,
        })
        .where(eq(schema.shifts.id, overlapping.id))
      shiftIds.set(demo.key, overlapping.id)
      continue
    }

    const weekStart = weekStartOf(localDateOf(startsAt, tz))
    let [schedule] = await db
      .select({ id: schema.schedules.id })
      .from(schema.schedules)
      .where(
        and(
          eq(schema.schedules.organizationId, org),
          eq(schema.schedules.locationId, locationId),
          eq(schema.schedules.weekStart, weekStart),
        ),
      )
    if (!schedule) {
      schedule = { id: newId() }
      await db.insert(schema.schedules).values({
        id: schedule.id,
        organizationId: org,
        locationId,
        weekStart,
        status: 'published',
        publishedVersion: 1,
        publishedAt: now,
      })
    }
    const id = newId()
    await db.insert(schema.shifts).values({
      id,
      organizationId: org,
      scheduleId: schedule.id,
      locationId,
      jobRoleId,
      stationId,
      startsAt,
      endsAt,
      breakMinutes: 30,
      assigneeEmploymentId: employmentId,
      publishedAt: new Date(now.getTime() - 3 * 24 * HOUR),
      publishedStartsAt: startsAt,
      publishedEndsAt: endsAt,
      publishedBreakMinutes: 30,
      publishedJobRoleId: jobRoleId,
      publishedStationId: stationId,
      publishedNotes: '',
      publishedAssigneeEmploymentId: employmentId,
      publishedIsOpen: false,
      publishedStatus: 'active',
    })
    shiftIds.set(demo.key, id)
  }

  // --- the work, generated exactly as a publish would -------------------------
  // The seed connection is the migration role outside a tenant transaction;
  // the query builder it offers is the same one generation uses.
  const generated = await generateForUpcomingShifts(
    db as unknown as Tx,
    org,
    null,
    null,
    new Date(now.getTime() - 3 * HOUR),
  )

  // --- what people have already done -----------------------------------------
  for (const state of seed.states) {
    const shiftId = shiftIds.get(state.shift)!
    const taskId = taskIds.get(`${state.template}::${state.task}`)
    if (!taskId) throw new Error(`Operations seed: no task "${state.task}" in "${state.template}"`)
    const [item] = await db
      .select()
      .from(schema.opsTaskItems)
      .where(
        and(
          eq(schema.opsTaskItems.organizationId, org),
          eq(schema.opsTaskItems.shiftId, shiftId),
          eq(schema.opsTaskItems.taskId, taskId),
        ),
      )
    if (!item)
      throw new Error(`Operations seed: "${state.task}" was not generated for ${state.shift}`)
    const owner = item.assignedEmploymentId!
    const at = new Date(Math.min(now.getTime() - 4 * 60_000, item.dueAt.getTime() + 2 * 60_000))
    const p = state.patch
    const by = 'by' in p && p.by ? person(p.by) : owner

    let set: Partial<typeof schema.opsTaskItems.$inferInsert>
    let action: 'completed' | 'submitted' | 'skipped' | 'blocked' | 'returned'
    let note = ''
    if (p.status === 'done') {
      set = {
        status: 'done',
        completedByEmploymentId: by,
        completedAt: at,
        responseText: p.text ?? '',
        responseNumber: p.number ?? null,
        verifiedByEmploymentId: p.verifiedBy ? person(p.verifiedBy) : null,
        verifiedAt: p.verifiedBy ? new Date(at.getTime() + 60_000) : null,
      }
      action = 'completed'
    } else if (p.status === 'awaiting_verification') {
      set = {
        status: p.status,
        completedByEmploymentId: by,
        completedAt: at,
        responseText: p.text ?? '',
        responseNumber: p.number ?? null,
      }
      action = 'submitted'
    } else if (p.status === 'skipped') {
      set = { status: 'skipped', completedByEmploymentId: by, completedAt: at, reason: p.reason }
      action = 'skipped'
      note = p.reason
    } else if (p.status === 'blocked') {
      set = { status: 'blocked', reason: p.reason }
      action = 'blocked'
      note = p.reason
    } else {
      set = { status: 'pending', returnedNote: p.returnedNote }
      action = 'returned'
      note = p.returnedNote
    }
    await db
      .update(schema.opsTaskItems)
      .set({ ...set, revision: item.revision + (p.status === 'pending' ? 2 : 1) })
      .where(eq(schema.opsTaskItems.id, item.id))
    if (p.status === 'pending') {
      await db.insert(schema.opsTaskEvents).values({
        id: newId(),
        organizationId: org,
        itemId: item.id,
        runId: item.runId,
        action: 'submitted',
        fromStatus: 'pending',
        toStatus: 'awaiting_verification',
        employmentId: owner,
        at: new Date(at.getTime() - 5 * 60_000),
      })
    }
    await db.insert(schema.opsTaskEvents).values({
      id: newId(),
      organizationId: org,
      itemId: item.id,
      runId: item.runId,
      action,
      fromStatus: p.status === 'pending' ? 'awaiting_verification' : 'pending',
      toStatus: set.status!,
      note,
      employmentId: p.status === 'pending' ? person(p.returnedBy) : by,
      at,
    })
    if ('verifiedBy' in p && p.verifiedBy) {
      await db.insert(schema.opsTaskEvents).values({
        id: newId(),
        organizationId: org,
        itemId: item.id,
        runId: item.runId,
        action: 'verified',
        fromStatus: 'done',
        toStatus: 'done',
        employmentId: person(p.verifiedBy),
        at: new Date(at.getTime() + 60_000),
      })
    }
  }

  // --- handoffs -----------------------------------------------------------------
  for (const h of seed.handoffs) {
    const tz = tzOf(h.location)
    const createdAt = new Date(now.getTime() - h.hoursAgo * HOUR)
    const id = newId()
    await db.insert(schema.handoffs).values({
      id,
      organizationId: org,
      locationId: place(h.location),
      shiftId: h.shift ? shiftIds.get(h.shift)! : null,
      businessDate: localDateOf(createdAt, tz),
      category: h.category,
      priority: h.urgent ? 'urgent' : 'normal',
      title: h.title,
      body: h.body,
      authorEmploymentId: person(h.author),
      status: h.resolved ? 'resolved' : 'open',
      resolvedByEmploymentId: h.resolved ? person(h.resolved.by) : null,
      resolvedAt: h.resolved ? new Date(now.getTime() - h.resolved.hoursAgo * HOUR) : null,
      resolutionNote: h.resolved?.note ?? '',
      createdAt,
      updatedAt: createdAt,
    })
    for (const reader of h.readBy ?? []) {
      await db.insert(schema.handoffAcknowledgements).values({
        id: newId(),
        organizationId: org,
        handoffId: id,
        employmentId: person(reader),
        acknowledgedAt: new Date(createdAt.getTime() + 2 * HOUR),
      })
    }
  }

  return {
    templates: seed.templates.length,
    runs: generated.created,
    handoffs: seed.handoffs.length,
  }
}
