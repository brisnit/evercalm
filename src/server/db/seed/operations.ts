/*
 * SHIFT OPERATIONS DEMO DATA.
 *
 * Published templates in each business's own words, then a real day of work:
 *
 *   Harbor & Vine   pre-shift lineup (uniform check, the 86 list, reservations
 *                   and large parties, manager notes), server side work, bar
 *                   setup and an overnight bar close, host stand setup
 *                   Downtown, and the closing handoff.
 *   Lumen Salon     appointment review and client notes at the desk, station
 *                   setup and sanitation, a product inventory count, closing
 *                   duties, the next-day handoff, and treatment-room turnover
 *                   in Boise, an hour ahead.
 *
 * Today's demo shifts are placed around the moment the seed runs, so there is
 * always a shift on now with finished, waiting, blocked, skipped and sent-back
 * work to look at. Work is generated by the SAME code a published schedule
 * uses; only the states people have already reached are written here.
 */

type SeedDb = NodePgDatabase<typeof schema>

interface TaskSeed {
  title: string
  instructions?: string
  optional?: boolean
  response?: 'check' | 'text' | 'number' | 'handoff'
  /** Minutes from the start (`start`) or the end (`end`) of the shift. */
  at: [anchor: 'start' | 'end', minutes: number]
  verify?: boolean
  shared?: boolean
}

interface TemplateSeed {
  name: string
  kind:
    'pre_shift' | 'opening' | 'side_work' | 'station_setup' | 'shift_duties' | 'closing' | 'handoff'
  description?: string
  locations: string[]
  jobRoles?: string[]
  stations?: { location: string; name: string }[]
  author: string
  sections: { title: string; tasks: TaskSeed[] }[]
}

interface DemoShift {
  key: string
  person: string
  location: string
  jobRole: string
  station?: string
  /** 'now': starts two hours before the seed runs. Otherwise a local clock time today. */
  start: string
  minutes: number
}

type ItemPatch =
  | { status: 'done'; by?: string; text?: string; number?: string; verifiedBy?: string }
  | { status: 'awaiting_verification'; by?: string; text?: string; number?: string }
  | { status: 'skipped'; by?: string; reason: string }
  | { status: 'blocked'; reason: string }
  | { status: 'pending'; returnedNote: string; returnedBy: string }

interface OperationsSeed {
  templates: TemplateSeed[]
  shifts: DemoShift[]
  states: { shift: string; template: string; task: string; patch: ItemPatch }[]
  handoffs: {
    location: string
    author: string
    shift?: string
    hoursAgo: number
    category: 'staffing' | 'inventory' | 'maintenance' | 'safety' | 'guest' | 'follow_up'
    urgent?: boolean
    title: string
    body: string
    resolved?: { by: string; note: string; hoursAgo: number }
    readBy?: string[]
  }[]
}

